"""
A run-time estimate for a lens model-fit, before it runs: `al.estimate_runtime(...)`.

The estimate joins three things:

- **The profiled per-evaluation cost** of the likelihood under the fit's compute setup, read from
  `autolens/config/runtime_estimates.yaml` (schema `runtime-estimates`, version 2). That file is
  generated by the autolens_profiling exporter (`scripts/misc/tooling/export_runtime_estimates.py
  --copy-to`) from the PyAutoPulse snapshot; it is never edited by hand.
- **The expected number of evaluations**, from the Nautilus heuristic of the calibrated wall model
  (`autolens.analysis.wall_model`, ported from autolens_inference `scripts/misc/wall/model.py`). Other
  samplers get no estimate.
- **The parallel efficiency** of numba workers under Nautilus (the curve in the yaml header).

Row matching (design call 2 of PyAutoLens#887):

1. Rows with the setup's `decision_id` and `setup_id` (a setup chosen by `setup="auto"`). When the setup
   has no decision (written by hand, or `PYAUTO_SETUP`), rows with its `setup_id`, the hardware class of
   the setup (its `hardware_class`, else `cpu_many_core` / `gpu_a100` by device) and the analysis's
   likelihood (`<dataset_type>/<variant>`, or every likelihood of the dataset type when unknown).
2. Among those, the nearest instrument by size, in log distance: the masked image pixels of an imaging
   dataset against `n_pixels_masked`, the visibilities of an interferometer dataset against `n_vis`.
3. When there is no size to match (point source, weak lensing, or a dataset giving none) and several
   rows remain, the estimate is a min-max band across them; the memory cap uses the largest
   `peak_rss_gb`.

The analyses report the estimate through `AnalysisRuntimeEstimate`, a mixin on the lens analyses that
resolve a setup (imaging, interferometer, point, weak). PyAutoFit calls its duck-typed
`runtime_estimate(search, model, number_of_cores)` after the fit's `Parallel:` banner and its
`resources_per_eval()` when it resolves `number_of_cores="auto"`.
"""

import functools
import logging
import math
from dataclasses import dataclass
from pathlib import Path
from typing import Dict, List, Optional, Tuple

import yaml

import autoarray as aa

from autolens.analysis import wall_model

logger = logging.getLogger(__name__)

RUNTIME_ESTIMATES_PATH = (
    Path(__file__).resolve().parent.parent / "config" / "runtime_estimates.yaml"
)

RUNTIME_ESTIMATES_SCHEMA = "runtime-estimates"
RUNTIME_ESTIMATES_VERSION = 2

EVALS_MODEL = "nautilus-heuristic"

#: Dataset types whose held-out check failed (interferometer 0.19-0.45x, weak 0.50-0.52x), plus datacube,
#: which has no phase-4 rows at all.
UNCALIBRATED_HELD_OUT = ("interferometer", "weak", "datacube")
UNCALIBRATED_NOTE = "uncalibrated (held-out 0.2–0.5×)"

#: Dataset types whose size is a visibility count; every other type is sized by masked image pixels.
VISIBILITY_DATASET_TYPES = ("interferometer", "datacube")

#: The dataset type of a point dataset whose positions fit is unknown: every `point_source_*` row.
POINT_DATASET_TYPE = "point"

HARDWARE_CLASS_BY_DEVICE = {"cpu": "cpu_many_core", "gpu": "gpu_a100"}


@functools.lru_cache(maxsize=None)
def _load(path: str) -> Tuple[Tuple[dict, ...], Dict[int, float], str]:
    with open(path) as f:
        data = yaml.safe_load(f)

    schema = data.get("schema") if isinstance(data, dict) else None
    version = data.get("version") if isinstance(data, dict) else None

    if schema != RUNTIME_ESTIMATES_SCHEMA or version != RUNTIME_ESTIMATES_VERSION:
        raise ValueError(
            f"The run-time estimates file {path} has schema {schema!r} version {version!r}; "
            f"PyAutoLens reads schema {RUNTIME_ESTIMATES_SCHEMA!r} version "
            f"{RUNTIME_ESTIMATES_VERSION}. Regenerate it with the autolens_profiling exporter "
            f"(scripts/misc/tooling/export_runtime_estimates.py --copy-to <PyAutoLens>)."
        )

    curve = wall_model.PARALLEL_EFFICIENCY
    header = data.get("parallel_efficiency") or {}
    try:
        if header.get("curve"):
            curve = {int(k): float(v) for k, v in header["curve"].items()}
    except (AttributeError, TypeError, ValueError):
        curve = wall_model.PARALLEL_EFFICIENCY

    return tuple(data.get("estimates") or ()), curve, str(data.get("tag"))


def load_runtime_estimates(path=None) -> dict:
    """
    The run-time estimates table, loaded once per path and cached.

    Returns a dict with `rows` (a list of row dicts), `curve` (the numba parallel-efficiency curve
    `{cores: efficiency}`, from the header or the ported fallback) and `tag` (the release pin the rows
    were profiled on).

    Raises
    ------
    ValueError
        If the file is not schema `runtime-estimates` version 2.
    """
    rows, curve, tag = _load(str(path or RUNTIME_ESTIMATES_PATH))
    return {"rows": [dict(row) for row in rows], "curve": dict(curve), "tag": tag}


@dataclass
class RuntimeEstimate:
    """
    A run-time estimate for one fit.

    `wall_seconds` is the central estimate (a matched or single row); for a band it is `None` and
    `wall_band` holds `(min, max)` seconds across the candidate rows. `ms_per_eval` is the profiled
    per-evaluation cost of the matched row (the lower end of the band otherwise; `ms_per_eval_band` holds
    both ends). `expected_evals` and the walls are `None` when the search is not Nautilus or the model is
    unknown.
    """

    ms_per_eval: Optional[float]
    record_id: Optional[str]
    instrument: Optional[str]
    matched_by: str
    expected_evals: Optional[int]
    evals_model: str
    parallel_efficiency: Optional[float]
    number_of_cores: int
    wall_seconds: Optional[float]
    wall_band: Optional[Tuple[float, float]]
    calibrated: bool
    note: Optional[str] = None
    likelihood: Optional[str] = None
    setup_id: Optional[str] = None
    backend: Optional[str] = None
    search_name: Optional[str] = None
    n_live: Optional[int] = None
    ms_per_eval_band: Optional[Tuple[float, float]] = None
    expected_evals_band: Optional[Tuple[int, int]] = None
    band_across: Optional[str] = None
    supported_search: bool = True
    has_profiling_cell: bool = True
    fallback_reason: Optional[str] = None

    @classmethod
    def no_profiling_cell(
        cls,
        setup_id: str,
        backend: Optional[str],
        number_of_cores: int,
        search=None,
        fallback_reason: Optional[str] = None,
    ) -> "RuntimeEstimate":
        """
        The estimate of a setup the run-time table has no row for (e.g. `numba_cpu_dense_fp64`): every
        number is `None` and `line()` reads `Estimate: no estimate for <setup_id> (no profiling cell)`.

        `fallback_reason` (e.g. `"JAX disabled"`) marks a `jax` setup that runs on numpy instead: the
        table has rows for the JAX designation only, so the fit that actually runs is not priced, and
        `line()` says why.
        """
        return cls(
            ms_per_eval=None,
            record_id=None,
            instrument=None,
            matched_by="none",
            expected_evals=None,
            evals_model="none",
            parallel_efficiency=None,
            number_of_cores=number_of_cores,
            wall_seconds=None,
            wall_band=None,
            calibrated=False,
            note="no profiling cell",
            setup_id=setup_id,
            backend=backend,
            search_name=None if search is None else type(search).__name__,
            has_profiling_cell=False,
            fallback_reason=fallback_reason,
        )

    def line(self) -> str:
        """
        The estimate as one log line, wall time first and the details in parentheses, e.g.

        `Estimate: ~6.4 min on this hardware   (283 ms/eval, euclid cell · Nautilus n_live=50 ≈ 4.6e3
        evals, heuristic · η=0.55)`

        A band reads `Estimate: ~4–11 min (no size match; range across instruments)   (...)`; a JAX
        fit has `1 worker (JAX)` in place of `η`; an uncalibrated estimate ends its details with
        `uncalibrated (held-out 0.2–0.5×)`; a search other than Nautilus reads
        `Estimate: none for Emcee (the run-time model covers Nautilus only)   (697 ms/eval, hst cell)`.
        The worker count is not repeated (the fit's `Parallel:` line reports it). A setup with no row in
        the run-time table reads `Estimate: no estimate for numba_cpu_dense_fp64 (no profiling cell)`.
        """
        if not self.has_profiling_cell and self.fallback_reason is not None:
            return _estimate_line(
                f"no estimate for {self.setup_id} (designated JAX; {self.fallback_reason}, "
                f"the numpy fallback has no profiling cell)",
                [],
            )

        if not self.has_profiling_cell:
            return _estimate_line(
                f"no estimate for {self.setup_id} (no profiling cell)", []
            )

        details = []

        if self.ms_per_eval_band is not None:
            low, high = self.ms_per_eval_band
            details.append(f"{_ms(low)}–{_ms(high)} ms/eval")
        elif self.ms_per_eval is not None:
            details.append(f"{_ms(self.ms_per_eval)} ms/eval, {self.instrument} cell")

        if not self.supported_search:
            head = (
                f"none for {self.search_name} (the run-time model covers Nautilus only)"
            )
            return _estimate_line(head, details)

        if self.expected_evals_band is not None:
            low, high = self.expected_evals_band
            details.append(
                f"Nautilus n_live={self.n_live} ≈ {_evals(low)}–{_evals(high)} evals, "
                f"heuristic"
            )
        elif self.expected_evals is not None:
            details.append(
                f"Nautilus n_live={self.n_live} ≈ {_evals(self.expected_evals)} evals, heuristic"
            )

        if self.parallel_efficiency is not None:
            details.append(f"η={self.parallel_efficiency:.2f}")
        elif self.backend == "jax":
            details.append("1 worker (JAX)")

        if not self.calibrated:
            details.append(self.note or UNCALIBRATED_NOTE)

        if self.wall_seconds is not None:
            head = f"~{_duration(self.wall_seconds)} on this hardware"
        elif self.wall_band is not None:
            low, high = self.wall_band
            head = (
                f"~{_duration_band(low, high)} (no size match; range across "
                f"{self.band_across or 'instruments'})"
            )
        elif details:
            # No wall time (the evaluation count is unknown): the per-evaluation cost leads.
            head, details = details[0], details[1:]
        else:
            head = "none"

        return _estimate_line(head, details)


def _estimate_line(head: str, details) -> str:
    """
    `Estimate: <head>   (<detail> · <detail> ...)`, the label padded to the width of the fit's
    `Setup:` / `Parallel:` labels; no parentheses when there are no details.
    """
    line = f"Estimate: {head}"
    if details:
        line += f"   ({' · '.join(details)})"
    return line


def _evals(value: int) -> str:
    mantissa, exponent = f"{value:.1e}".split("e")
    return f"{mantissa}e{int(exponent)}"


def _ms(value: float) -> str:
    if value >= 10:
        return f"{value:.0f}"
    return f"{value:.2g}"


def _unit(seconds: float) -> Tuple[float, str]:
    if seconds < 90:
        return 1.0, "s"
    if seconds < 90 * 60:
        return 60.0, "min"
    if seconds < 48 * 3600:
        return 3600.0, "h"
    return 86400.0, "d"


def _fmt(value: float) -> str:
    return f"{value:.0f}" if value >= 10 else f"{value:.2g}"


def _duration(seconds: float) -> str:
    scale, unit = _unit(seconds)
    return f"{_fmt(seconds / scale)} {unit}"


def _duration_band(low: float, high: float) -> str:
    scale, unit = _unit(high)
    return f"{_fmt(low / scale)}–{_fmt(high / scale)} {unit}"


def _is_nautilus(search) -> bool:
    try:
        import autofit as af

        if isinstance(search, af.Nautilus):
            return True
    except Exception:
        pass
    return "nautilus" in type(search).__name__.lower()


def _n_live(search) -> Optional[int]:
    n_live = getattr(search, "n_live", None)
    if n_live is None:
        try:
            from autonerves import conf

            n_live = conf.instance["non_linear"]["nest"]["Nautilus"]["search"]["n_live"]
        except Exception:
            n_live = None
    try:
        return int(n_live) if n_live is not None else None
    except (TypeError, ValueError):
        return None


def dataset_type_from(dataset) -> Optional[str]:
    """
    The dataset type of the run-time table for a dataset: `imaging`, `interferometer`, `weak`, `point`
    (the family `point_source_image` / `point_source_source`, which the positions fit decides) or `None`
    for an unknown dataset.
    """
    if isinstance(dataset, aa.Imaging):
        return "imaging"
    if isinstance(dataset, aa.Interferometer):
        return "interferometer"
    from autolens.weak.dataset import WeakDataset

    if isinstance(dataset, WeakDataset):
        return "weak"
    from autolens.point.dataset import PointDataset

    if isinstance(dataset, PointDataset):
        return POINT_DATASET_TYPE
    return None


def likelihood_from(dataset, model) -> Optional[str]:
    """
    The `<dataset_type>/<variant>` likelihood of a dataset and model, as the setup rules key it, or
    `None` when it cannot be worked out (a point dataset needs its analysis's positions fit).
    """
    from autolens.point.dataset import PointDataset

    if isinstance(dataset, PointDataset):
        return None

    dataset_type = dataset_type_from(dataset)

    if dataset_type == "weak":
        return "weak/isothermal"

    if dataset_type in ("imaging", "interferometer") and model is not None:
        try:
            from autogalaxy.analysis import setup_util

            key, _ = setup_util.setup_key_and_note_from(dataset=dataset, model=model)
            return "/".join(key)
        except Exception:
            return None

    return None


def dataset_size_from(dataset, dataset_type: Optional[str]) -> Optional[float]:
    """
    The size the run-time table matches instruments by: visibilities for an interferometer (or datacube)
    dataset, masked image pixels for every imaging-type dataset; `None` when the dataset gives none.
    """
    if dataset is None:
        return None
    try:
        if dataset_type in VISIBILITY_DATASET_TYPES:
            uv = getattr(dataset, "uv_wavelengths", None)
            if uv is not None:
                return float(uv.shape[0])
            return float(len(dataset.data))
        mask = getattr(dataset, "mask", None)
        if mask is not None and hasattr(mask, "pixels_in_mask"):
            return float(mask.pixels_in_mask)
    except Exception:
        return None
    return None


def candidate_rows(
    setup: aa.Setup,
    likelihood: Optional[str] = None,
    dataset_type: Optional[str] = None,
    rows: Optional[List[dict]] = None,
) -> List[dict]:
    """
    The run-time table rows a setup can be priced by, before size matching (see the module docstring).
    """
    rows = load_runtime_estimates()["rows"] if rows is None else rows

    setup_id = setup.setup_id

    if setup.decision_id is not None:
        matched = [
            row
            for row in rows
            if row.get("decision_id") == setup.decision_id
            and row.get("setup_id") == setup_id
        ]
        if matched:
            return matched

    hardware_class = setup.hardware_class or HARDWARE_CLASS_BY_DEVICE.get(setup.device)

    def wanted(row):
        if row.get("setup_id") != setup_id:
            return False
        if hardware_class is not None and row.get("hardware_class") != hardware_class:
            return False
        row_likelihood = row.get("likelihood") or ""
        if likelihood is not None:
            return row_likelihood == likelihood
        if dataset_type == POINT_DATASET_TYPE:
            return row_likelihood.startswith("point_source_")
        if dataset_type is not None:
            return row_likelihood.split("/")[0] == dataset_type
        return True

    return [row for row in rows if wanted(row)]


def match_rows(
    candidates: List[dict], size: Optional[float]
) -> Tuple[List[dict], str]:
    """
    The rows a fit is priced by and how they were chosen: `"single"` (one candidate), `"size"` (the
    nearest instrument by log size) or `"band"` (several rows, no size to tell them apart).
    """
    if len(candidates) <= 1:
        return candidates, "single"

    if size is not None and size > 0:
        sized = []
        for row in candidates:
            dataset_type = _row_dataset_type(row)
            field = (
                "n_vis" if dataset_type in VISIBILITY_DATASET_TYPES else "n_pixels_masked"
            )
            value = row.get(field)
            if value:
                sized.append((abs(math.log(size) - math.log(float(value))), row))
        if sized:
            nearest = min(distance for distance, _ in sized)
            matched = [row for distance, row in sized if distance == nearest]
            if len(matched) == 1:
                return matched, "size"
            return matched, "band"

    return candidates, "band"


def _row_dataset_type(row: dict) -> str:
    return (row.get("likelihood") or "").split("/")[0]


def _per_call_s(row: dict) -> float:
    override = wall_model.PER_CALL_OVERRIDE.get(row.get("record_id"))
    if override is not None:
        return override[0]
    return float(row["ms_per_eval"]) / 1000.0


def _wall_s(row: dict, evals: int, backend: str, cores: int, curve) -> float:
    likelihood = row.get("likelihood") or "/"
    dataset_type, _, variant = likelihood.partition("/")
    per_eval = wall_model.PER_EVAL_OVERRIDE.get(
        (dataset_type, variant, row.get("host_class"))
    )
    if per_eval is not None:
        stage = evals * per_eval[0]
    else:
        price = wall_model.effective_per_call(
            _per_call_s(row), backend=backend, cores=cores, curve=curve
        )
        stage = wall_model.stage_seconds(evals, price)
    return wall_model.job_seconds([stage])


def matched_rows_for(
    dataset, model, setup: aa.Setup, likelihood: Optional[str] = None, rows=None
) -> Tuple[List[dict], List[dict], str]:
    """
    `(candidates, matched, matched_by)` for a dataset, model and setup: the candidate rows of
    `candidate_rows` and the rows `match_rows` prices the fit by.
    """
    if likelihood is None:
        likelihood = likelihood_from(dataset=dataset, model=model)

    dataset_type = (
        likelihood.split("/")[0] if likelihood else dataset_type_from(dataset)
    )

    candidates = candidate_rows(
        setup=setup, likelihood=likelihood, dataset_type=dataset_type, rows=rows
    )

    candidate_types = {_row_dataset_type(row) for row in candidates}
    if len(candidate_types) == 1:
        dataset_type = candidate_types.pop()

    matched, matched_by = match_rows(
        candidates, dataset_size_from(dataset, dataset_type)
    )
    return candidates, matched, matched_by


def _rule_key_from(dataset, model, likelihood: Optional[str]) -> Tuple[str, str]:
    """
    The `(dataset_type, variant)` rule key of `aa.Setup.auto` for `setup="auto"`: the one the analyses
    use (`autogalaxy.analysis.setup_util.setup_key_and_note_from` for imaging and interferometer,
    `weak/isothermal` for weak lensing), or the `likelihood` the caller gives.

    Raises
    ------
    ValueError
        When the key cannot be worked out (a point dataset needs `likelihood=`, as its rule depends on
        the analysis's positions fit).
    """
    if likelihood is not None:
        dataset_type, _, variant = likelihood.partition("/")
        return dataset_type, variant

    dataset_type = dataset_type_from(dataset)

    if dataset_type in ("imaging", "interferometer"):
        from autogalaxy.analysis import setup_util

        key, _ = setup_util.setup_key_and_note_from(dataset=dataset, model=model)
        return key

    if dataset_type == "weak":
        return "weak", "isothermal"

    raise ValueError(
        "setup='auto' cannot work out the setup rule for this dataset"
        + (
            ": a point dataset's rule depends on its positions fit, so pass likelihood="
            "'point_source_image/image_plane' or 'point_source_source/source_plane'."
            if dataset_type == POINT_DATASET_TYPE
            else f" ({type(dataset).__name__}); pass likelihood='<dataset_type>/<variant>'."
        )
    )


def resolve_setup_from(dataset, model, setup, likelihood: Optional[str] = None):
    """
    The compute setup of `estimate_runtime`: `None`, an `aa.Setup` or setup_id string as given, or for
    `"auto"` the setup a fit's `setup="auto"` resolves to, `aa.Setup.auto` with the analyses' rule key
    (`_rule_key_from`) on the detected hardware (`PYAUTO_SETUP` overrides it, as in a fit).
    """
    from autogalaxy.analysis import setup_util

    setup = setup_util.setup_input_from(setup)

    if setup != setup_util.SETUP_AUTO:
        return setup

    key = _rule_key_from(dataset=dataset, model=model, likelihood=likelihood)
    return aa.Setup.auto(*key, environment=setup_util.setup_environment())


def estimate_runtime(
    dataset,
    model,
    search,
    setup,
    number_of_cores=1,
    likelihood: Optional[str] = None,
) -> Optional[RuntimeEstimate]:
    """
    Estimate how long a Nautilus fit of `model` to `dataset` under the compute `setup` takes.

    Parameters
    ----------
    dataset
        The dataset fitted (an `al.Imaging`, `al.Interferometer`, `al.PointDataset` or
        `al.WeakDataset`), used for its dataset type and size.
    model
        The model fitted: its `prior_count` sets the dimension of the Nautilus heuristic and its
        pixelization the likelihood variant.
    search
        The non-linear search: only `af.Nautilus` gets an estimate (its `n_live`); any other search gets
        an estimate whose line says there is none.
    setup
        The compute setup: an `al.Setup`, a setup_id string (e.g. `"numba_cpu_sparse_fp64"`) or `"auto"`,
        resolved as a fit's `setup="auto"` is (`aa.Setup.auto` with the analyses' rule key for the dataset
        and model on the detected hardware; `PYAUTO_SETUP` overrides it).
    number_of_cores
        The worker count of the fit, an int or `"auto"` (resolved as a fit resolves it, by PyAutoFit's
        `resolve_number_of_cores`: 1 for a JAX backend, else the detected cores capped by the matched row's
        `cpus_per_eval` / `peak_rss_gb`). For a numba setup the per-call is divided by
        `cores * efficiency(cores)`; a JAX setup runs one worker and uses its per-call as is.
    likelihood
        The `<dataset_type>/<variant>` likelihood, when the caller knows it (the analyses pass their setup
        rule key); otherwise it is worked out from the dataset and model.

    Returns
    -------
    A `RuntimeEstimate`, or `None` when there is no setup. A setup the table has no row for gives an
    estimate whose `line()` reads `no estimate for <setup_id> (no profiling cell)`.
    """
    setup = resolve_setup_from(
        dataset=dataset, model=model, setup=setup, likelihood=likelihood
    )
    if setup is None:
        return None

    table = load_runtime_estimates()
    curve = table["curve"]

    candidates, matched, matched_by = matched_rows_for(
        dataset=dataset,
        model=model,
        setup=setup,
        likelihood=likelihood,
        rows=table["rows"],
    )

    backend = setup.backend
    cores = _number_of_cores_from(
        number_of_cores=number_of_cores,
        setup=setup,
        resources=resources_per_eval_from(matched, matched_by),
    )

    from autogalaxy.analysis import setup_util

    # A `jax` setup run on numpy (`PYAUTO_DISABLE_JAX=1` or JAX not installed) is not what the JAX
    # rows measured, so it is not priced by them (the `Setup:` line reports the same fallback).
    fallback_reason = setup_util.jax_fallback_reason_from(
        setup=setup, use_jax=setup_util.use_jax_from(backend == "jax")
    )
    if fallback_reason is not None:
        return RuntimeEstimate.no_profiling_cell(
            setup_id=setup.setup_id,
            backend="numpy",
            number_of_cores=cores,
            search=search,
            fallback_reason=fallback_reason,
        )

    if not candidates:
        return RuntimeEstimate.no_profiling_cell(
            setup_id=setup.setup_id,
            backend=backend,
            number_of_cores=cores,
            search=search,
        )

    efficiency = (
        wall_model.parallel_efficiency(cores, curve=curve)
        if backend == "numba"
        else None
    )

    matched_types = sorted({_row_dataset_type(r) for r in matched})
    held_out = [t for t in matched_types if t in UNCALIBRATED_HELD_OUT]
    no_factor = [
        t
        for t in matched_types
        if t not in wall_model.EVALS_FACTOR and t not in UNCALIBRATED_HELD_OUT
    ]
    calibrated = not held_out and not no_factor
    if calibrated:
        note = None
    elif held_out:
        note = UNCALIBRATED_NOTE
    else:
        note = f"uncalibrated (no evaluations factor for {', '.join(no_factor)})"

    ms_values = [float(row["ms_per_eval"]) for row in matched]
    is_band = matched_by == "band"
    row = matched[0]

    likelihoods = {r.get("likelihood") for r in matched}
    band_across = "instruments" if len(likelihoods) == 1 else "likelihoods"

    estimate = RuntimeEstimate(
        ms_per_eval=min(ms_values) if is_band else float(row["ms_per_eval"]),
        record_id=None if is_band else row.get("record_id"),
        instrument=None if is_band else row.get("instrument"),
        matched_by=matched_by,
        expected_evals=None,
        evals_model=EVALS_MODEL,
        parallel_efficiency=efficiency,
        number_of_cores=cores,
        wall_seconds=None,
        wall_band=None,
        calibrated=calibrated,
        note=note,
        likelihood=row.get("likelihood") if len(likelihoods) == 1 else None,
        setup_id=setup.setup_id,
        backend=backend,
        search_name=type(search).__name__,
        ms_per_eval_band=(min(ms_values), max(ms_values)) if is_band else None,
        band_across=band_across if is_band else None,
    )

    if not _is_nautilus(search):
        estimate.supported_search = False
        estimate.evals_model = "none"
        estimate.note = (
            f"no estimate for {type(search).__name__} (run-time model covers Nautilus only)"
        )
        return estimate

    n_live = _n_live(search)
    prior_count = getattr(model, "prior_count", None)
    estimate.n_live = n_live

    if n_live is None or not prior_count:
        return estimate

    evals = [
        wall_model.stage_evals(int(prior_count), n_live, _row_dataset_type(r))
        for r in matched
    ]
    estimate.expected_evals = evals[0]
    if min(evals) != max(evals):
        estimate.expected_evals = min(evals)
        estimate.expected_evals_band = (min(evals), max(evals))

    walls = [_wall_s(r, e, backend, cores, curve) for r, e in zip(matched, evals)]

    if is_band:
        estimate.wall_band = (min(walls), max(walls))
    else:
        estimate.wall_seconds = walls[0]

    return estimate


def _number_of_cores_from(number_of_cores, setup: aa.Setup, resources: Optional[dict]) -> int:
    """
    The worker count `estimate_runtime` prices a fit by: 1 for a setup whose backend resolves to JAX
    (after `PYAUTO_DISABLE_JAX` and a missing JAX install, as in a fit), else the request, with `"auto"`
    resolved by PyAutoFit's `resolve_number_of_cores` exactly as a fit resolves it (the detected cores,
    capped by the matched row's `cpus_per_eval` / `peak_rss_gb`).
    """
    from types import SimpleNamespace

    from autofit.non_linear.parallel.pool import resolve_number_of_cores
    from autofit.non_linear.parallel.resources import is_auto
    from autogalaxy.analysis import setup_util

    is_jax = setup_util.use_jax_from(setup.backend == "jax")

    if is_auto(number_of_cores):
        # A stand-in analysis carrying what `resolve_number_of_cores` duck-types: the setup and the
        # matched row's resources.
        analysis = SimpleNamespace(
            setup=setup, is_jax=is_jax, resources_per_eval=lambda: resources
        )
        return resolve_number_of_cores(
            requested=number_of_cores,
            analysis=analysis,
            is_jax=is_jax,
            where="estimate_runtime",
        ).number_of_cores

    if is_jax:
        return 1
    return max(1, int(number_of_cores or 1))


def resources_per_eval_from(rows: List[dict], matched_by: str) -> Optional[dict]:
    """
    `{"cpus_per_eval", "peak_rss_gb"}` of the matched row, or for a band the largest of each across the
    candidate rows (the conservative memory cap); `None` when neither is known.
    """
    if not rows:
        return None

    def largest(name):
        values = [r.get(name) for r in rows if r.get(name)]
        return max(values) if values else None

    if matched_by == "band":
        cpus, peak = largest("cpus_per_eval"), largest("peak_rss_gb")
    else:
        cpus, peak = rows[0].get("cpus_per_eval"), rows[0].get("peak_rss_gb")

    if cpus is None and peak is None:
        return None
    return {"cpus_per_eval": cpus, "peak_rss_gb": peak}


class AnalysisRuntimeEstimate:
    """
    Mixin giving a lens analysis that resolves a compute `setup` the two PyAutoFit hooks of the
    run-time estimator:

    - `runtime_estimate(search, model, number_of_cores)`: the one `Estimate:` line PyAutoFit logs after
      the fit's `Parallel:` banner (`autofit.non_linear.search.runtime.resolve_fit_parallel`).
    - `resources_per_eval()`: `{"cpus_per_eval", "peak_rss_gb"}` of the matched profiling row, which
      PyAutoFit uses to cap `number_of_cores="auto"` on a non-JAX analysis.

    Both return `None` when the analysis has no resolved setup, and neither ever raises. The mixin goes
    first in the bases so its `resolve_setup` (which remembers the model, for the likelihood variant)
    wraps PyAutoGalaxy's `AnalysisSetupMixin.resolve_setup`.
    """

    def resolve_setup(self, model, log_banner: bool = True):
        self._runtime_estimate_model = model
        return super().resolve_setup(model=model, log_banner=log_banner)

    def _runtime_likelihood_from(self, model) -> Optional[str]:
        """
        The `<dataset_type>/<variant>` setup rule key of this analysis, or `None` when unknown. A point or
        weak analysis keys on its own settings (`setup_key_from`); an imaging or interferometer analysis
        needs the model for its variant.
        """
        try:
            if hasattr(self, "setup_key_from"):
                key = self.setup_key_from(model)
            elif model is None:
                return None
            else:
                key = self.setup_key_and_note_from(model)[0]
            return "/".join(key)
        except Exception:
            return None

    def _runtime_estimate_from(self, search, model, number_of_cores):
        setup = getattr(self, "setup", None)
        if setup is None:
            return None
        if model is None:
            model = getattr(self, "_runtime_estimate_model", None)
        return estimate_runtime(
            dataset=getattr(self, "dataset", None),
            model=model,
            search=search,
            setup=setup,
            number_of_cores=number_of_cores,
            likelihood=self._runtime_likelihood_from(model),
        )

    def runtime_estimate(self, search, model=None, number_of_cores=1) -> Optional[str]:
        """
        The `Estimate:` line for this fit (see `al.estimate_runtime`), or `None` without a setup.
        """
        try:
            estimate = self._runtime_estimate_from(search, model, number_of_cores)
        except Exception as e:
            logger.debug(f"Run-time estimate failed and was ignored: {e!r}")
            return None
        # A setup with no profiling cell logs nothing at fit time (as before); only a direct
        # `al.estimate_runtime` call reports "no estimate for <setup_id> (no profiling cell)".
        if estimate is None or not estimate.has_profiling_cell:
            return None
        return estimate.line()

    def resources_per_eval(self) -> Optional[dict]:
        """
        `{"cpus_per_eval", "peak_rss_gb"}` of the profiling row matched to this analysis's setup and
        dataset (the largest across the candidate rows when no row is matched), or `None` without a setup.
        """
        try:
            setup = getattr(self, "setup", None)
            if setup is None:
                return None
            # A `jax` setup run on numpy is not what the JAX rows measured (see `estimate_runtime`).
            if setup.backend == "jax" and not self.is_jax:
                return None
            model = getattr(self, "_runtime_estimate_model", None)
            _, matched, matched_by = matched_rows_for(
                dataset=getattr(self, "dataset", None),
                model=model,
                setup=setup,
                likelihood=self._runtime_likelihood_from(model),
            )
            return resources_per_eval_from(matched, matched_by)
        except Exception as e:
            logger.debug(f"resources_per_eval failed and was ignored: {e!r}")
            return None
